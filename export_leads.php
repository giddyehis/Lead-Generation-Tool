    </style>
</head>
<body>
    <div class="header">
        <h1>Lead Generation Report</h1>
        <p>Generated on ' . date('Y-m-d H:i:s') . '</p>
    </div>';

        // Summary Statistics
        $html .= '<div class="section">
        <h2>Summary Statistics</h2>
        <div class="stats">
            <div class="stat-card">
                <div class="stat-number">' . $report['summary']['total_leads'] . '</div>
                <div>Total Leads</div>
            </div>
            <div class="stat-card">
                <div class="stat-number">' . $report['summary']['valid_leads'] . '</div>
                <div>Valid Leads</div>
            </div>
            <div class="stat-card">
                <div class="stat-number">' . $report['summary']['high_quality_leads'] . '</div>
                <div>High Quality</div>
            </div>
            <div class="stat-card">
                <div class="stat-number">' . $report['summary']['leads_with_email'] . '</div>
                <div>With Email</div>
            </div>
        </div>
    </div>';

        // Quality Distribution
        $html .= '<div class="section">
        <h2>Quality Distribution</h2>
        <table>
            <tr><th>Quality Level</th><th>Count</th><th>Percentage</th></tr>';
        
        foreach ($report['summary']['quality_distribution'] as $quality => $count) {
            $percentage = $report['summary']['total_leads'] > 0 ? round(($count / $report['summary']['total_leads']) * 100, 1) : 0;
            $html .= '<tr><td>' . $quality . '</td><td>' . $count . '</td><td>' . $percentage . '%</td></tr>';
        }
        
        $html .= '</table></div>';

        // Top Sources
        if (!empty($report['sources'])) {
            $html .= '<div class="section">
            <h2>Top Data Sources</h2>
            <table>
                <tr><th>Source</th><th>Leads Count</th></tr>';
            
            foreach ($report['sources'] as $source => $count) {
                $html .= '<tr><td>' . htmlspecialchars($source) . '</td><td>' . $count . '</td></tr>';
            }
            
            $html .= '</table></div>';
        }

        // Top Companies
        if (!empty($report['top_companies'])) {
            $html .= '<div class="section">
            <h2>Top Companies</h2>
            <table>
                <tr><th>Company</th><th>Leads Count</th></tr>';
            
            foreach ($report['top_companies'] as $company => $count) {
                $html .= '<tr><td>' . htmlspecialchars($company) . '</td><td>' . $count . '</td></tr>';
            }
            
            $html .= '</table></div>';
        }

        // Top Locations
        if (!empty($report['top_locations'])) {
            $html .= '<div class="section">
            <h2>Top Locations</h2>
            <table>
                <tr><th>Location</th><th>Leads Count</th></tr>';
            
            foreach ($report['top_locations'] as $location => $count) {
                $html .= '<tr><td>' . htmlspecialchars($location) . '</td><td>' . $count . '</td></tr>';
            }
            
            $html .= '</table></div>';
        }

        $html .= '</body></html>';

        $filepath = $this->config->storage['export_path'] . $filename . '_report.html';
        file_put_contents($filepath, $html);

        return $filepath;
    }
}

// Handle export request
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        $exporter = new LeadExporter();
        
        // Get leads from the generation process
        $generator = new LeadGenerator();
        $result = $generator->generateLeads($_POST);
        
        if (!$result['success']) {
            throw new Exception($result['message']);
        }

        $format = $_POST['export_format'] ?? 'csv';
        $filename = 'leads_' . date('Y-m-d_H-i-s');
        
        $exporter->exportLeads($result['leads'], $format, $filename);
        
    } catch (Exception $e) {
        header('Content-Type: application/json');
        echo json_encode([
            'success' => false,
            'message' => $e->getMessage()
        ]);
    }
} else {
    header('Content-Type: application/json');
    echo json_encode([
        'success' => false,
        'message' => 'Invalid request method'
    ]);
}
